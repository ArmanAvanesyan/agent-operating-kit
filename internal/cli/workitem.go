const workItemMarker = "<!-- Generated by AOK work-item scaffold. Do not edit directly. -->"
const workItemGenerator = "aok-work-item-scaffold"

var workItemProviders = []string{"neutral", "github", "azure-devops"}

// runWorkItem provides the read-only catalog query. Mutating scaffold operations
// are implemented separately so discovery never gains implicit write authority.
func runWorkItem(args []string, stdout, stderr io.Writer) (int, error) {
	usage := func(w io.Writer) {
		fmt.Fprintln(w, "Usage: aok work-item list [--flow <flow> [--overlay <overlay>...]] [--json]\n       aok work-item scaffold <project> [--flow <flow>] [--overlay <overlay>...] [--provider github,azure-devops] [--force] [--json]\n       aok work-item validate <project> [--json]")
	}
	if len(args) == 0 || args[0] == "help" || args[0] == "--help" {
		usage(stdout)
		return 0, nil
	}
	if args[0] == "scaffold" {
		return runWorkItemScaffold(args[1:], stdout, stderr)
	}
	if args[0] == "validate" {
		return runWorkItemValidate(args[1:], stdout, stderr)
	}
	if args[0] != "list" {
		usage(stderr)
		return 2, nil
	}
	flow, jsonOut := "", false
	overlays := []string{}
	for i := 1; i < len(args); i++ {
		switch args[i] {
		case "--json":
			jsonOut = true
		case "--flow":
			if flow != "" || i+1 >= len(args) {
				usage(stderr)
				return 2, nil
			}
			i++
			flow = args[i]
		case "--overlay":
			if i+1 >= len(args) {
				usage(stderr)
				return 2, nil
			}
			i++
			overlays = append(overlays, args[i])
		default:
			usage(stderr)
			return 2, nil
		}
	}
	if flow == "" && len(overlays) > 0 {
		return 1, fmt.Errorf("--overlay requires --flow")
	}
	root, e := requireRoot()
	if e != nil {
		return 1, e
	}
	path := filepath.Join(root, "work-items", "catalog.json")
	catalog, e := readJSON(path)
	if e != nil {
		return 1, e
	}
	all, ok := catalog["types"].([]any)
	if !ok {
		return 1, fmt.Errorf("Work-item catalog types must be an object array")
	}
	selection := any(nil)
	items := all
	if flow != "" {
		profiles, e := loadMethodProfiles(root)
		if e != nil {
			return 1, e
		}
		support := ""
		kind := ""
		available := map[string]bool{}
		for _, p := range profiles {
			id := str(p["id"])
			available[id] = true
			if id == flow {
				support = str(p["supportLevel"])
				kind = str(p["kind"])
			}
		}
		if !available[flow] {
			return 1, fmt.Errorf("Unknown methodology flow: %s", flow)
		}
		if kind != "flow" {
			return 1, fmt.Errorf("Methodology profile %q is not a flow", flow)
		}
		if support != "active" && support != "scaffolded" {
			return 1, fmt.Errorf("Methodology flow %q is %s; only active or scaffolded flows have work-item templates", flow, support)
		}
		seen := map[string]bool{}
		for _, o := range overlays {
			if seen[o] {
				return 1, fmt.Errorf("Duplicate methodology overlays: %s", o)
			}
			seen[o] = true
			if !available[o] {
				return 1, fmt.Errorf("Unknown methodology overlay: %s", o)
			}
			for _, p := range profiles {
				if str(p["id"]) == o && str(p["kind"]) != "overlay" {
					return 1, fmt.Errorf("Methodology profile %q is not an overlay", o)
				}
			}
		}
		if support == "scaffolded" && len(overlays) > 0 {
			return 1, fmt.Errorf("Methodology flow %q is scaffolded; overlays cannot be composed with scaffolded work-item exports in this slice", flow)
		}
		selection = map[string]any{"flow": flow, "overlays": overlays}
		allowed := map[string]bool{"core:core": true, "flow:" + flow: true}
		for _, o := range overlays {
			allowed["overlay:"+o] = true
		}
		items = []any{}
		for _, v := range all {
			o := obj(obj(v)["origin"])
			if allowed[str(o["kind"])+":"+str(o["id"])] {
				items = append(items, v)
			}
		}
	}
	result := map[string]any{"kind": "aok-work-item-type-list", "catalogVersion": catalog["version"], "catalogCount": len(all), "selection": selection, "effectiveCount": len(items), "types": items}
	if jsonOut {
		return 0, json.NewEncoder(stdout).Encode(result)
	}
	if selection != nil {
		fmt.Fprintf(stdout, "Flow: %s\nOverlays: %s\n", flow, strings.Join(overlays, ", "))
		if len(overlays) == 0 {
			fmt.Fprintln(stdout, "Overlays: none")
		}
	}
	fmt.Fprintf(stdout, "Work-item types: %d\n", len(items))
	for _, v := range items {
		i := obj(v)
		o := obj(i["origin"])
		fmt.Fprintf(stdout, "- %s: %s (%s:%s -> %s)\n", i["id"], i["displayName"], o["kind"], o["id"], i["canonicalCategory"])
	}
	return 0, nil
}

func runWorkItemScaffold(args []string, out, errw io.Writer) (int, error) {
	if len(args) == 0 {
		return 2, nil
	}
	target, e := filepath.Abs(args[0])
	if e != nil {
		return 1, e
	}
	flow, provider := "", "all"
	overlays := []string{}
	force, jsonOut := false, false
	for i := 1; i < len(args); i++ {
		switch args[i] {
		case "--flow":
			if flow != "" || i+1 >= len(args) {
				return 2, nil
			}
			i++
			flow = args[i]
		case "--overlay":
			if i+1 >= len(args) {
				return 2, nil
			}
			i++
			overlays = append(overlays, args[i])
		case "--provider":
			if i+1 >= len(args) {
				return 2, nil
			}
			i++
			provider = args[i]
		case "--force":
			force = true
		case "--json":
			jsonOut = true
		default:
			fmt.Fprintln(errw, "invalid work-item scaffold arguments")
			return 2, nil
		}
	}
	st, e := os.Stat(target)
	if e != nil || !st.IsDir() {
		return 1, fmt.Errorf("Target is not a directory: %s", target)
	}
	root, e := requireRoot()
	if e != nil {
		return 1, e
	}
	cat, e := readJSON(filepath.Join(root, "work-items", "catalog.json"))
	if e != nil {
		return 1, e
	}
	all, ok := cat["types"].([]any)
	if !ok {
		return 1, fmt.Errorf("Work-item catalog types must be an object array")
	}
	selection, e := projectWorkItemSelection(root, target, flow, overlays)
	if e != nil {
		return 1, e
	}
	providers := []string{}
	switch provider {
	case "all":
		providers = append(providers, workItemProviders...)
	case "neutral", "github", "azure-devops":
		providers = []string{provider}
	default:
		return 1, fmt.Errorf("Unsupported work-item provider: %s", provider)
	}
	items := effectiveWorkItems(all, selection)
	assets, e := renderWorkItemAssets(root, target, cat, items, selection, providers)
	if e != nil {
		return 1, e
	}
	manifestPath := filepath.Join(target, ".aok", "work-item-scaffold.json")
	old, e := readWorkManifest(manifestPath, target)
	if e != nil {
		return 1, e
	}
	owned := str(old["generatedBy"]) == workItemGenerator && str(old["kind"]) == "aok-work-item-scaffold-manifest"
	oldFiles := map[string]string{}
	if owned {
		for _, v := range arr(old["files"]) {
			f := obj(v)
			oldFiles[str(f["path"])] = str(f["sha256"])
		}
	}
	newSet := map[string]bool{}
	for p := range assets {
		newSet[p] = true
	}
	stale := []string{}
	for p := range oldFiles {
		if !newSet[p] {
			stale = append(stale, p)
		}
	}
	sort.Strings(stale)
	conflicts := []string{}
	for p, content := range assets {
		dest := filepath.Join(target, p)
		if !safeWorkItemPath(target, dest) {
			return 1, fmt.Errorf("Work-item scaffold output escapes target: %s", p)
		}
		b, er := strictReadFile(dest)
		if er == nil && string(b) != content && !(oldFiles[p] != "" && workItemFileIsGenerated(b, oldFiles[p], dest)) {
			conflicts = append(conflicts, p)
		} else if er != nil && !os.IsNotExist(er) {
			return 1, er
		}
	}
	for _, p := range stale {
		dest := filepath.Join(target, p)
		if !safeWorkItemPath(target, dest) {
			return 1, fmt.Errorf("Recorded work-item output escapes target: %s", p)
		}
		b, er := strictReadFile(dest)
		if er == nil && !workItemFileIsGenerated(b, oldFiles[p], dest) {
			conflicts = append(conflicts, p)
		} else if er != nil && !os.IsNotExist(er) {
			return 1, er
		}
	}
	if len(old) > 0 && !owned {
		conflicts = append(conflicts, filepath.ToSlash(filepath.Join(".aok", "work-item-scaffold.json")))
	}
	sort.Strings(conflicts)
	if len(conflicts) > 0 && !force {
		return 1, fmt.Errorf("Refusing to overwrite modified or conflicting work-item scaffold files: %s; use --force to back them up", strings.Join(uniqueStrings(conflicts), ", "))
	}
	stamp := time.Now().UTC().Format("20060102150405.000000")
	stamp = strings.ReplaceAll(stamp, ".", "")
	backupRoot := filepath.Join(target, ".aok-backups", stamp)
	changes := []map[string]string{}
	if len(old) > 0 && !owned {
		b, _ := strictReadFile(manifestPath)
		backup, er := backupWorkItemFile(manifestPath, b, backupRoot, target)
		if er != nil {
			return 1, er
		}
		changes = append(changes, map[string]string{"path": ".aok/work-item-scaffold.json", "status": "updated", "backup": backup})
	}
	for _, p := range stale {
		dest := filepath.Join(target, p)
		b, er := strictReadFile(dest)
		if os.IsNotExist(er) {
			continue
		}
		if er != nil {
			return 1, er
		}
		c := map[string]string{"path": p, "status": "removed"}
		if force && !workItemFileIsGenerated(b, oldFiles[p], dest) {
			bk, er := backupWorkItemFile(dest, b, backupRoot, target)
			if er != nil {
				return 1, er
			}
			c["backup"] = bk
		}
		if er = os.Remove(dest); er != nil {
			return 1, er
		}
		changes = append(changes, c)
	}
	paths := make([]string, 0, len(assets))
	for p := range assets {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		content := assets[p]
		dest := filepath.Join(target, p)
		b, er := strictReadFile(dest)
		if er == nil && string(b) == content {
			changes = append(changes, map[string]string{"path": p, "status": "unchanged"})
			continue
		}
		if er != nil && !os.IsNotExist(er) {
			return 1, er
		}
		c := map[string]string{"path": p, "status": "created"}
		if er == nil {
			c["status"] = "updated"
			if !(oldFiles[p] != "" && workItemFileIsGenerated(b, oldFiles[p], dest)) {
				bk, er := backupWorkItemFile(dest, b, backupRoot, target)
				if er != nil {
					return 1, er
				}
				c["backup"] = bk
			}
		}
		if er = os.MkdirAll(filepath.Dir(dest), 0755); er != nil {
			return 1, er
		}
		if er = os.WriteFile(dest, []byte(content), 0644); er != nil {
			return 1, er
		}
		changes = append(changes, c)
	}
	files := []any{}
	for _, p := range paths {
		files = append(files, map[string]string{"path": p, "sha256": workItemHash([]byte(assets[p]))})
	}
	mf := map[string]any{"generatedBy": workItemGenerator, "kind": "aok-work-item-scaffold-manifest", "catalogVersion": cat["version"], "selection": selection, "providers": providers, "files": files}
	mb, e := json.MarshalIndent(mf, "", "  ")
	if e != nil {
		return 1, e
	}
	if e = os.MkdirAll(filepath.Dir(manifestPath), 0755); e != nil {
		return 1, e
	}
	if e = os.WriteFile(manifestPath, append(mb, '\n'), 0644); e != nil {
		return 1, e
	}
	result := map[string]any{"kind": "aok-work-item-scaffold", "projectPath": target, "selection": selection, "providers": providers, "effectiveCount": len(items), "projectManifestChanged": false, "remoteMutation": false, "manifestPath": ".aok/work-item-scaffold.json", "files": changes}
	if jsonOut {
		return 0, json.NewEncoder(out).Encode(result)
	}
	fmt.Fprintf(out, "Scaffolded work-item templates for %s\n- flow: %s\n- overlays: %s\n- providers: %s\n- project methodology: unchanged\n- remote resources: unchanged\n", target, selection["flow"], strings.Join(overlays, ", "), strings.Join(providers, ", "))
	if len(overlays) == 0 {
		fmt.Fprintln(out, "- overlays: none")
	}
	for _, c := range changes {
		suffix := ""
		if c["backup"] != "" {
			suffix = "; backup " + c["backup"]
		}
		fmt.Fprintf(out, "- %s %s%s\n", c["status"], c["path"], suffix)
	}
	return 0, nil
}

func runWorkItemValidate(args []string, out, errw io.Writer) (int, error) {
	if len(args) == 0 {
		return 2, nil
	}
	target, e := filepath.Abs(args[0])
	if e != nil {
		return 1, e
	}
	jsonOut := false
	for _, a := range args[1:] {
		if a == "--json" {
			jsonOut = true
		} else if a == "--help" || a == "-h" {
			return 0, nil
		} else {
			return 2, nil
		}
	}
	report := validateWorkItemScaffold(target)
	if jsonOut {
		if e = json.NewEncoder(out).Encode(report); e != nil {
			return 1, e
		}
	} else {
		sel := obj(report["selection"])
		over := []string{}
		for _, v := range arr(sel["overlays"]) {
			over = append(over, str(v))
		}
		providers := []string{}
		for _, v := range arr(report["providers"]) {
			providers = append(providers, str(v))
		}
		status := "passed"
		if report["valid"] != true {
			status = "failed"
		}
		fmt.Fprintf(out, "Work-item validation: %s\nFlow: %s\nOverlays: %s\nProviders: %s\n", status, defaultString(str(sel["flow"]), "<unknown>"), defaultString(strings.Join(over, ", "), "none"), defaultString(strings.Join(providers, ", "), "none"))
		for _, v := range arr(report["checks"]) {
			c := obj(v)
			detail := ""
			if str(c["detail"]) != "" {
				detail = " - " + str(c["detail"])
			}
			fmt.Fprintf(out, "- %s: %s%s\n", c["name"], c["status"], detail)
		}
	}
	if report["valid"] != true {
		return 1, nil
	}
	return 0, nil
}

func projectWorkItemSelection(root, target, flow string, overlays []string) (map[string]any, error) {
	if flow == "" {
		if len(overlays) > 0 {
			return nil, fmt.Errorf("--overlay requires an explicit --flow")
		}
		m, e := readJSON(filepath.Join(target, ".aok", "project.json"))
		if e != nil {
			return nil, fmt.Errorf("project methodology selection is missing: %w", e)
		}
		s := obj(m["methodology"])
		flow = str(s["flow"])
		for _, v := range arr(s["overlays"]) {
			overlays = append(overlays, str(v))
		}
		if flow == "" {
			flow = "kanban"
		}
	}
	ps, e := loadMethodProfiles(root)
	if e != nil {
		return nil, e
	}
	known := map[string]methodProfile{}
	for _, p := range ps {
		known[str(p["id"])] = p
	}
	p := known[flow]
	if p == nil {
		return nil, fmt.Errorf("Unknown methodology flow: %s", flow)
	}
	if str(p["kind"]) != "flow" {
		return nil, fmt.Errorf("Methodology profile %q is not a flow", flow)
	}
	if str(p["supportLevel"]) != "active" && str(p["supportLevel"]) != "scaffolded" {
		return nil, fmt.Errorf("Methodology flow %q is %s; only active or scaffolded flows have work-item templates", flow, p["supportLevel"])
	}
	if str(p["supportLevel"]) == "scaffolded" && len(overlays) > 0 {
		return nil, fmt.Errorf("Methodology flow %q is scaffolded; overlays cannot be composed with scaffolded work-item exports in this slice", flow)
	}
	seen := map[string]bool{}
	for _, o := range overlays {
		if seen[o] {
			return nil, fmt.Errorf("Duplicate methodology overlays: %s", o)
		}
		seen[o] = true
		x := known[o]
		if x == nil {
			return nil, fmt.Errorf("Unknown methodology overlay: %s", o)
		}
		if str(x["kind"]) != "overlay" {
			return nil, fmt.Errorf("Methodology profile %q is not an overlay", o)
		}
		if str(x["supportLevel"]) != "active" {
			return nil, fmt.Errorf("Methodology overlay %q is %s", o, x["supportLevel"])
		}
		compatible := arr(x["compatibleFlows"])
		if len(compatible) > 0 {
			ok := false
			for _, v := range compatible {
				if str(v) == flow {
					ok = true
				}
			}
			if !ok {
				return nil, fmt.Errorf("Methodology overlay %q is incompatible with flow %q", o, flow)
			}
		}
	}
	return map[string]any{"flow": flow, "overlays": overlays}, nil
}

func effectiveWorkItems(all []any, s map[string]any) []any {
	allowed := map[string]bool{"core:core": true, "flow:" + str(s["flow"]): true}
	for _, v := range arr(s["overlays"]) {
		allowed["overlay:"+str(v)] = true
	}
	items := []any{}
	for _, v := range all {
		o := obj(obj(v)["origin"])
		if allowed[str(o["kind"])+":"+str(o["id"])] {
			items = append(items, v)
		}
	}
	return items
}

func renderWorkItemAssets(root, target string, cat map[string]any, items []any, selection map[string]any, providers []string) (map[string]string, error) {
	assets := map[string]string{}
	common := arr(cat["commonSections"])
	azure := "$defaultRequirementWorkItemType"
	manifest, e := readJSON(filepath.Join(target, ".aok", "project.json"))
	if e == nil {
		b := obj(manifest["workSystem"])
		if str(b["provider"]) == "azure-devops" && str(b["supportLevel"]) == "scaffolded" && str(b["verifiedAt"]) != "" {
			wit := obj(b["workItemType"])
			azure = defaultString(str(wit["name"]), defaultString(str(wit["referenceName"]), azure))
		}
	}
	for _, it := range items {
		i := obj(it)
		sections := append(append([]any{}, common...), arr(i["sections"])...)
		sourcePath := filepath.Clean(filepath.Join(root, "work-items", str(i["sourcePath"])))
		if !within(filepath.Join(root, "work-items"), sourcePath) {
			return nil, fmt.Errorf("Work-item template escapes catalog root")
		}
		b, e := strictReadFile(sourcePath)
		if e != nil {
			return nil, fmt.Errorf("Work-item template is missing: %s", sourcePath)
		}
		source := strings.TrimSpace(string(b))
		id, name, desc := str(i["id"]), str(i["displayName"]), str(i["description"])
		origin := obj(i["origin"])
		if containsString(providers, "neutral") {
			lines := []string{workItemMarker, "# " + name, "", "AOK work-item type: `" + id + "`", "Canonical category: `" + str(i["canonicalCategory"]) + "`", "Origin: `" + str(origin["kind"]) + ":" + str(origin["id"]) + "`", "", source}
			for _, v := range sections {
				s := obj(v)
				req := "Optional"
				if s["required"] == true {
					req = "Required"
				}
				lines = append(lines, "", "## "+str(s["label"]), "", "<!-- "+req+": "+str(s["description"])+" -->", "")
			}
			assets[filepath.ToSlash(filepath.Join("agents", "tasks", "types", "aok-"+id+".md"))] = strings.TrimRight(strings.Join(lines, "\n"), "\n") + "\n"
		}
		if containsString(providers, "github") {
			m := obj(obj(i["providerMappings"])["github"])
			lines := []string{"# Generated by AOK work-item scaffold. Do not edit directly.", "name: " + yamlString(name), "description: " + yamlString(desc), "type: " + yamlString(str(m["issueType"])), "body:", "  - type: markdown", "    attributes:", "      value: |-", "        **AOK work-item type:** `" + id + "`", "", "        " + desc, ""}
			for _, l := range strings.Split(source, "\n") {
				lines = append(lines, "        "+l)
			}
			for _, v := range sections {
				s := obj(v)
				control := "input"
				if s["multiline"] == true {
					control = "textarea"
				}
				lines = append(lines, "  - type: "+control, "    id: "+str(s["id"]), "    attributes:", "      label: "+yamlString(str(s["label"])), "      description: "+yamlString(str(s["description"])))
				if control == "textarea" {
					lines = append(lines, "      placeholder: |-", "        Provide concrete, reviewable details.")
				} else {
					lines = append(lines, "      placeholder: "+yamlString("Required detail"))
				}
				required := "false"
				if s["required"] == true {
					required = "true"
				}
				lines = append(lines, "    validations:", "      required: "+required)
			}
			assets[filepath.ToSlash(filepath.Join(".github", "ISSUE_TEMPLATE", "aok-"+id+".yml"))] = strings.TrimRight(strings.Join(lines, "\n"), "\n") + "\n"
		}
		if containsString(providers, "azure-devops") {
			m := obj(obj(i["providerMappings"])["azureDevOps"])
			native := str(m["workItemType"])
			if native == "$defaultRequirementWorkItemType" {
				native = azure
			}
			lines := []string{workItemMarker, "# " + name + " — Azure DevOps", "", "> This document is desired-state guidance. It does not install or modify an Azure DevOps process or work-item template.", "", "- AOK work-item type: `" + id + "`", "- Canonical category: `" + str(i["canonicalCategory"]) + "`", "- Azure work-item type: `" + native + "`", "", source}
			for _, v := range sections {
				s := obj(v)
				req := "optional"
				if s["required"] == true {
					req = "required"
				}
				lines = append(lines, "", "## "+str(s["label"]), "", "Field intent: "+str(s["description"])+" ("+req+").", "")
			}
			assets[filepath.ToSlash(filepath.Join("docs", "aok", "work-items", "azure-devops", "aok-"+id+".md"))] = strings.TrimRight(strings.Join(lines, "\n"), "\n") + "\n"
		}
	}
	for _, provider := range []string{"github", "azure-devops"} {
		if !containsString(providers, provider) {
			continue
		}
		maps := []any{}
		for _, v := range items {
			i := obj(v)
			native := ""
			if provider == "github" {
				native = str(obj(obj(i["providerMappings"])["github"])["issueType"])
			} else {
				native = str(obj(obj(i["providerMappings"])["azureDevOps"])["workItemType"])
				if native == "$defaultRequirementWorkItemType" {
					native = azure
				}
			}
			maps = append(maps, map[string]any{"aokType": i["id"], "canonicalCategory": i["canonicalCategory"], "providerType": native})
		}
		// Python's oracle preserves insertion order in these generated documents;
		// use a struct so Go emits the identical byte order.
		d := struct {
			GeneratedBy                    string         `json:"generatedBy"`
			Kind                           string         `json:"kind"`
			RemoteMutation                 bool           `json:"remoteMutation"`
			Selection                      map[string]any `json:"selection"`
			Mappings                       []any          `json:"mappings"`
			DefaultRequirementWorkItemType string         `json:"defaultRequirementWorkItemType,omitempty"`
		}{GeneratedBy: workItemGenerator, Kind: "aok-" + provider + "-work-item-desired-state", RemoteMutation: false, Selection: selection, Mappings: maps}
		rel := filepath.Join("docs", "aok", "work-items", provider, "desired-state.json")
		if provider == "github" {
			rel = filepath.Join("docs", "aok", "work-items", "github", "desired-state.json")
		}
		if provider == "azure-devops" {
			d.DefaultRequirementWorkItemType = azure
		}
		b, e := json.MarshalIndent(d, "", "  ")
		if e != nil {
			return nil, e
		}
		assets[filepath.ToSlash(rel)] = string(b) + "\n"
	}
	return assets, nil
}

func yamlString(s string) string   { b, _ := json.Marshal(s); return string(b) }
func workItemHash(b []byte) string { h := sha256.Sum256(b); return hex.EncodeToString(h[:]) }
func workItemFileIsGenerated(b []byte, expected, path string) bool {
	if expected != "" && workItemHash(b) != expected {
		return false
	}
	s := string(b)
	if strings.HasPrefix(s, workItemMarker) || strings.HasPrefix(s, "# Generated by AOK work-item scaffold.") {
		return true
	}
	if strings.EqualFold(filepath.Ext(path), ".json") {
		m := map[string]any{}
		return strictDecodeJSON(b, &m) == nil && str(m["generatedBy"]) == workItemGenerator
	}
	return false
}
func readWorkManifest(path, target string) (map[string]any, error) {
	if st, e := os.Lstat(path); e == nil && st.Mode()&os.ModeSymlink != 0 {
		return nil, fmt.Errorf("Work-item scaffold manifest must not be a symlink: %s", path)
	}
	if !safeWorkItemPath(target, path) {
		return nil, fmt.Errorf("Work-item scaffold manifest escapes target: %s", path)
	}
	m, e := readJSON(path)
	if os.IsNotExist(e) {
		return map[string]any{}, nil
	}
	if e != nil {
		return nil, e
	}
	return m, nil
}

func safeWorkItemPath(base, path string) bool {
	absBase, e := filepath.Abs(base)
	if e != nil {
		return false
	}
	absPath, e := filepath.Abs(path)
	if e != nil || !within(absBase, absPath) {
		return false
	}
	probe := absPath
	for {
		resolved, er := filepath.EvalSymlinks(probe)
		if er == nil {
			return within(absBase, resolved)
		}
		if !os.IsNotExist(er) {
			return false
		}
		parent := filepath.Dir(probe)
		if parent == probe {
			return false
		}
		probe = parent
	}
}
func backupWorkItemFile(path string, b []byte, backupRoot, target string) (string, error) {
	rel, e := filepath.Rel(target, path)
	if e != nil {
		return "", e
	}
	backup := filepath.Join(backupRoot, rel)
	if e = os.MkdirAll(filepath.Dir(backup), 0755); e != nil {
		return "", e
	}
	if e = os.WriteFile(backup, b, 0644); e != nil {
		return "", e
	}
	return filepath.ToSlash(filepath.Join(".aok-backups", filepath.Base(backupRoot), rel)), nil
}
func uniqueStrings(in []string) []string {
	out := []string{}
	for _, s := range in {
		if len(out) == 0 || out[len(out)-1] != s {
			out = append(out, s)
		}
	}
	return out
}
func containsString(a []string, s string) bool {
	for _, v := range a {
		if v == s {
			return true
		}
	}
	return false
}
func defaultString(v, d string) string {
	if v == "" {
		return d
	}
	return v
}

func validateWorkItemScaffold(target string) map[string]any {
	report := map[string]any{"kind": "aok-work-item-validation", "projectPath": target, "valid": true, "selection": nil, "providers": []any{}, "checks": []any{}}
	checks := []any{}
	add := func(name, status, detail string) {
		c := map[string]any{"name": name, "status": status}
		if detail != "" {
			c["detail"] = detail
		}
		checks = append(checks, c)
		if status != "satisfied" {
			report["valid"] = false
		}
	}
	root, e := requireRoot()
	if e != nil {
		add("manifest", "invalid", e.Error())
		report["checks"] = checks
		return report
	}
	path := filepath.Join(target, ".aok", "work-item-scaffold.json")
	m, e := readWorkManifest(path, target)
	if e != nil {
		add("manifest", "invalid", e.Error())
		report["checks"] = checks
		return report
	}
	if len(m) == 0 {
		add("manifest", "missing", "")
		report["checks"] = checks
		return report
	}
	if str(m["generatedBy"]) != workItemGenerator || str(m["kind"]) != "aok-work-item-scaffold-manifest" {
		add("manifest", "invalid", "unknown generator or manifest kind")
		report["checks"] = checks
		return report
	}
	add("manifest", "satisfied", "")
	cat, e := readJSON(filepath.Join(root, "work-items", "catalog.json"))
	if e != nil {
		add("contract", "invalid", e.Error())
		report["checks"] = checks
		return report
	}
	sel := obj(m["selection"])
	report["selection"] = m["selection"]
	report["providers"] = arr(m["providers"])
	flow := str(sel["flow"])
	overlays := []string{}
	for _, v := range arr(sel["overlays"]) {
		overlays = append(overlays, str(v))
	}
	normalized, e := projectWorkItemSelection(root, target, flow, overlays)
	if e != nil {
		add("contract", "invalid", e.Error())
		report["checks"] = checks
		return report
	}
	normb, _ := json.Marshal(normalized)
	selb, _ := json.Marshal(sel)
	if string(normb) != string(selb) {
		add("contract", "invalid", "manifest selection is not normalized")
		report["checks"] = checks
		return report
	}
	providers := []string{}
	for _, v := range arr(m["providers"]) {
		providers = append(providers, str(v))
	}
	if len(providers) == 0 {
		add("contract", "invalid", "manifest providers must be a non-empty array")
		report["checks"] = checks
		return report
	}
	if len(uniqueStrings(append([]string(nil), providers...))) != len(providers) {
		add("contract", "invalid", "manifest providers are invalid or duplicated")
		report["checks"] = checks
		return report
	}
	canonical := []string{}
	for _, p := range workItemProviders {
		if containsString(providers, p) {
			canonical = append(canonical, p)
		}
	}
	if strings.Join(canonical, "\x00") != strings.Join(providers, "\x00") {
		add("contract", "invalid", "manifest providers are not in canonical order")
		report["checks"] = checks
		return report
	}
	for _, p := range providers {
		if !containsString(workItemProviders, p) {
			add("contract", "invalid", "manifest providers are invalid or duplicated")
			report["checks"] = checks
			return report
		}
	}
	all := arr(cat["types"])
	items := effectiveWorkItems(all, normalized)
	assets, e := renderWorkItemAssets(root, target, cat, items, normalized, providers)
	if e != nil {
		add("contract", "invalid", e.Error())
		report["checks"] = checks
		return report
	}
	paths := make([]string, 0, len(assets))
	for p := range assets {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	files := []any{}
	for _, p := range paths {
		files = append(files, map[string]string{"path": p, "sha256": workItemHash([]byte(assets[p]))})
	}
	if m["catalogVersion"] != cat["version"] {
		add("contract", "invalid", "catalog version is stale")
		report["checks"] = checks
		return report
	}
	recorded := arr(m["files"])
	rb, _ := json.Marshal(recorded)
	eb, _ := json.Marshal(files)
	if string(rb) != string(eb) {
		add("contract", "invalid", "recorded file set or hashes do not match the current catalog")
		report["checks"] = checks
		return report
	}
	add("contract", "satisfied", "")
	for _, v := range recorded {
		f := obj(v)
		rel := str(f["path"])
		dest := filepath.Join(target, rel)
		if !safeWorkItemPath(target, dest) {
			add(rel, "invalid", "recorded path escapes target")
			continue
		}
		b, e := strictReadFile(dest)
		switch {
		case os.IsNotExist(e):
			add(rel, "missing", "")
		case e != nil:
			add(rel, "invalid", e.Error())
		case !workItemFileIsGenerated(b, "", dest):
			add(rel, "unmarked", "")
		case workItemHash(b) != str(f["sha256"]):
			add(rel, "mismatched", "")
		default:
			add(rel, "satisfied", "")
		}
	}
	report["checks"] = checks
	return report
}
