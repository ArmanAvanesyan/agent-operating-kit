func TestWorkItemScaffoldHashOwnershipAndValidation(t *testing.T) {
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	t.Setenv("AOK_ROOT", root)
	project := t.TempDir()
	if err = os.MkdirAll(filepath.Join(project, ".aok"), 0755); err != nil {
		t.Fatal(err)
	}
	if err = os.WriteFile(filepath.Join(project, ".aok", "project.json"), []byte(`{"methodology":{"flow":"kanban","overlays":[]}}`), 0644); err != nil {
		t.Fatal(err)
	}
	var out, stderr bytes.Buffer
	code, err := runWorkItem([]string{"scaffold", project, "--provider", "neutral", "--json"}, &out, &stderr)
	if err != nil || code != 0 {
		t.Fatalf("scaffold = %d, %v: %s", code, err, stderr.String())
	}
	var result map[string]any
	if err = json.Unmarshal(out.Bytes(), &result); err != nil {
		t.Fatal(err)
	}
	files := arr(result["files"])
	if len(files) == 0 {
		t.Fatal("no scaffold outputs")
	}
	target := filepath.Join(project, "agents", "tasks", "types", "aok-bug.md")
	if _, err = os.Stat(target); err != nil {
		t.Fatal(err)
	}
	out.Reset()
	code, err = runWorkItem([]string{"validate", project, "--json"}, &out, &stderr)
	if err != nil || code != 0 {
		t.Fatalf("validate = %d, %v: %s", code, err, out.String())
	}
	if err = os.WriteFile(target, []byte("manual edit\n"), 0644); err != nil {
		t.Fatal(err)
	}
	out.Reset()
	code, err = runWorkItem([]string{"scaffold", project, "--provider", "neutral", "--json"}, &out, &stderr)
	if err == nil || code == 0 {
		t.Fatal("manual edit was overwritten without force")
	}
	out.Reset()
	code, err = runWorkItem([]string{"scaffold", project, "--provider", "neutral", "--force", "--json"}, &out, &stderr)
	if err != nil || code != 0 {
		t.Fatalf("forced scaffold = %d, %v", code, err)
	}
	matches, err := filepath.Glob(filepath.Join(project, ".aok-backups", "*", "agents", "tasks", "types", "aok-bug.md"))
	if err != nil || len(matches) != 1 {
		t.Fatalf("backup files %v, %v", matches, err)
	}
}

func TestWorkItemGeneratedBytesMatchPythonOracle(t *testing.T) {
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	t.Setenv("AOK_ROOT", root)
	goProject, pyProject := t.TempDir(), t.TempDir()
	for _, p := range []string{goProject, pyProject} {
		if err = os.MkdirAll(filepath.Join(p, ".aok"), 0755); err != nil {
			t.Fatal(err)
		}
		if err = os.WriteFile(filepath.Join(p, ".aok", "project.json"), []byte(`{"methodology":{"flow":"kanban","overlays":[]}}`), 0644); err != nil {
			t.Fatal(err)
		}
	}
	var out, stderr bytes.Buffer
	if code, e := runWorkItem([]string{"scaffold", goProject, "--provider", "all", "--json"}, &out, &stderr); e != nil || code != 0 {
		t.Fatalf("Go scaffold %d %v %s", code, e, stderr.String())
	}
	cmd := exec.Command("python3", filepath.Join(root, "scripts", "aok"), "work-item", "scaffold", pyProject, "--provider", "all", "--json")
	cmd.Env = append(os.Environ(), "AOK_ROOT="+root)
	pyOut, e := cmd.CombinedOutput()
	if e != nil {
		t.Fatalf("Python oracle: %v: %s", e, pyOut)
	}
	var gm, pm map[string]any
	if e = json.Unmarshal([]byte(mustRead(t, filepath.Join(goProject, ".aok", "work-item-scaffold.json"))), &gm); e != nil {
		t.Fatal(e)
	}
	if e = json.Unmarshal([]byte(mustRead(t, filepath.Join(pyProject, ".aok", "work-item-scaffold.json"))), &pm); e != nil {
		t.Fatal(e)
	}
	gf, pf := arr(gm["files"]), arr(pm["files"])
	if len(gf) != len(pf) {
		t.Fatalf("manifest file counts Go=%d Python=%d", len(gf), len(pf))
	}
	for i := range gf {
		g, p := obj(gf[i]), obj(pf[i])
		if g["path"] != p["path"] || g["sha256"] != p["sha256"] {
			t.Fatalf("manifest parity mismatch at %d: Go=%v Python=%v", i, g, p)
		}
		for _, pair := range [][2]string{{goProject, str(g["path"])}, {pyProject, str(p["path"])}} {
			if _, e := os.Stat(filepath.Join(pair[0], filepath.FromSlash(pair[1]))); e != nil {
				t.Fatal(e)
			}
		}
		gb := mustRead(t, filepath.Join(goProject, filepath.FromSlash(str(g["path"]))))
		pb := mustRead(t, filepath.Join(pyProject, filepath.FromSlash(str(p["path"]))))
		if gb != pb {
			t.Fatalf("generated bytes differ: %s", g["path"])
		}
	}
}
func mustRead(t *testing.T, path string) string {
	t.Helper()
	b, e := os.ReadFile(path)
	if e != nil {
		t.Fatal(e)
	}
	return string(b)
}

func TestMethodologyValidatorsMatchPythonJSONOracle(t *testing.T) {
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	t.Setenv("AOK_ROOT", root)
	cases := [][]string{
		{"validate-feature", "--name", "  Generate   PDF   for   Invoice  ", "--json"},
		{"validate-requirement", "--id", "REQ-014", "--outcome", " Produce customer-ready invoice PDF ", "--project-moscow", "must", "--acceptance", "The generated PDF matches approved invoice content", "--json"},
		{"validate-iteration", "--id", "I-12", "--stage", "construction", "--objective", "Deliver invoice generation increment", "--work-item", "use-case=UC-03", "--discipline", "model=docs/architecture.md", "--discipline", "implementation=PR-142", "--discipline", "test=reports/test-results.xml", "--discipline", "deployment=not-applicable:No-release-activity", "--discipline", "configuration-management=build-142", "--discipline", "project-management=docs/iteration-plan.md", "--discipline", "environment=ci/run-912", "--json"},
	}
	for _, args := range cases {
		t.Run(args[0], func(t *testing.T) {
			var goOut, goErr bytes.Buffer
			code, e := runMethodology(args, &goOut, &goErr)
			if e != nil || code != 0 {
				t.Fatalf("Go command %d %v: %s", code, e, goErr.String())
			}
			pyArgs := append([]string{"methodology"}, args...)
			cmd := exec.Command("python3", append([]string{filepath.Join(root, "scripts", "aok")}, pyArgs...)...)
			cmd.Env = append(os.Environ(), "AOK_ROOT="+root)
			pyOut, e := cmd.CombinedOutput()
			if e != nil {
				t.Fatalf("Python oracle %v: %s", e, pyOut)
			}
			var got, want any
			if e = json.Unmarshal(goOut.Bytes(), &got); e != nil {
				t.Fatal(e)
			}
			if e = json.Unmarshal(pyOut, &want); e != nil {
				t.Fatal(e)
			}
			gb, _ := json.Marshal(got)
			wb, _ := json.Marshal(want)
			if string(gb) != string(wb) {
				t.Fatalf("JSON differs\nGo: %s\nPython: %s", gb, wb)
			}
		})
	}
}

func TestMethodologyTransitionCLIUsesInjectedJournalAndEvidence(t *testing.T) {
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	t.Setenv("AOK_ROOT", root)
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	profile, err := lifecycleProfile(root, "fdd", func(e methodology.Evidence) error {
		if e.SHA256 != methodology.Digest([]byte(e.Gate)) {
			return fmt.Errorf("bad gate proof")
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	key := "fdd-project-manager"
	tr := methodology.Transition{Version: methodology.LifecycleVersion, ID: "transition-1", Subject: "feature-1", Profile: "fdd", From: "build-features-list", To: "plan-by-feature", ExpectedRevision: 0, Role: key, Signer: "test-key", Evidence: []methodology.Evidence{{Gate: "approve-feature-list", SHA256: methodology.Digest([]byte("approve-feature-list"))}}}
	body, err := methodology.CanonicalTransitionBytes(tr)
	if err != nil {
		t.Fatal(err)
	}
	tr.Signature = hex.EncodeToString(ed25519.Sign(priv, body))
	b, err := json.Marshal(tr)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(t.TempDir(), "transition.json")
	if err = os.WriteFile(path, b, 0600); err != nil {
		t.Fatal(err)
	}
	keys := func(s, r string) (ed25519.PublicKey, bool) { return pub, s == "test-key" && r == key }
	current := methodology.Snapshot{Subject: "feature-1", Profile: "fdd", Stage: "build-features-list", Revision: 0}
	services := &MethodologyLifecycleServices{Snapshot: func(context.Context, string) (methodology.Snapshot, error) { return current, nil }, Keys: keys, VerifyEvidence: profile.VerifyEvidence, Now: func() time.Time { return time.Unix(1, 0) }}
	var out, stderr bytes.Buffer
	code, err := runMethodologyWithServices(context.Background(), []string{"check-transition", "--transition", path, "--json"}, services, &out, &stderr)
	if err != nil || code != 0 {
		t.Fatalf("check %d %v %s", code, err, stderr.String())
	}
	called := false
	services.Record = func(_ context.Context, p methodology.Profile, got methodology.Transition, k methodology.KeyResolver, at time.Time) (methodology.Snapshot, error) {
		called = true
		return methodology.RecordTransition(p, current, got, k, func(_ uint64, n methodology.Snapshot, _ methodology.Transition) error {
			if at.Unix() != 1 {
				return fmt.Errorf("clock not injected")
			}
			return nil
		})
	}
	out.Reset()
	code, err = runMethodologyWithServices(context.Background(), []string{"record-transition", "--transition", path, "--json"}, services, &out, &stderr)
	if err != nil || code != 0 || !called {
		t.Fatalf("record %d %v called=%v: %s", code, err, called, stderr.String())
	}
}

