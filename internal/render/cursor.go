package render

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var slugRe = regexp.MustCompile(`[^a-z0-9]+`)

func cursorSlug(raw string) string {
	s := strings.ToLower(strings.TrimSpace(raw))
	s = slugRe.ReplaceAllString(s, "-")
	s = strings.Trim(s, "-")
	if s == "" {
		return "item"
	}
	return s
}

// writeCursorNativeTree emits a project-local Cursor tree alongside the generic
// import bundle: .cursor/rules/*.mdc, .cursor/skills/*/SKILL.md, and a
// non-executable hooks checklist. Does not emit .cursor/hooks.json (AOK hook
// commands are host-checklists, not Cursor hook scripts).
func writeCursorNativeTree(bundleDir, packDir string, content map[string]any) ([]string, error) {
	var files []string

	roles := asMapSlice(content["roles"])
	if len(roles) > 0 {
		rulesDir := filepath.Join(bundleDir, ".cursor", "rules")
		if err := os.MkdirAll(rulesDir, 0o755); err != nil {
			return nil, err
		}
		for _, role := range roles {
			id := orString(role["id"], orString(role["callsign"], orString(role["name"], "role")))
			slug := cursorSlug(id)
			rel := filepath.ToSlash(filepath.Join(".cursor", "rules", slug+".mdc"))
			path := filepath.Join(bundleDir, filepath.FromSlash(rel))
			body := cursorRoleMDC(role)
			if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
				return nil, err
			}
			files = append(files, rel)
		}
	}

	skills := asMapSlice(content["skills"])
	for _, skill := range skills {
		id := orString(skill["id"], orString(skill["name"], "skill"))
		slug := cursorSlug(id)
		relDir := filepath.ToSlash(filepath.Join(".cursor", "skills", slug))
		skillDir := filepath.Join(bundleDir, filepath.FromSlash(relDir))
		if err := os.MkdirAll(skillDir, 0o755); err != nil {
			return nil, err
		}
		rel := relDir + "/SKILL.md"
		path := filepath.Join(bundleDir, filepath.FromSlash(rel))
		body, err := cursorSkillMD(packDir, skill, slug)
		if err != nil {
			return nil, err
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			return nil, err
		}
		files = append(files, rel)
	}

	hooks := asMapSlice(content["hooks"])
	if len(hooks) > 0 {
		rel := ".cursor/hooks-checklist.md"
		path := filepath.Join(bundleDir, filepath.FromSlash(rel))
		if err := os.WriteFile(path, []byte(cursorHooksChecklist(hooks)), 0o644); err != nil {
			return nil, err
		}
		files = append(files, rel)
	}

	return files, nil
}

func cursorRoleMDC(role map[string]any) string {
	name := orString(role["name"], orString(role["callsign"], orString(role["id"], "Role")))
	callsign := orString(role["callsign"], orString(role["id"], ""))
	desc := fmt.Sprintf("AOK role: %s", name)
	if callsign != "" && callsign != name {
		desc = fmt.Sprintf("AOK role: %s (%s)", name, callsign)
	}

	var b strings.Builder
	b.WriteString("---\n")
	b.WriteString(fmt.Sprintf("description: %q\n", desc))
	b.WriteString("alwaysApply: false\n")
	b.WriteString("---\n\n")
	b.WriteString(fmt.Sprintf("# %s\n\n", name))
	if callsign != "" {
		b.WriteString(fmt.Sprintf("Callsign: `%s`\n\n", callsign))
	}
	if resp, ok := role["responsibilities"].([]any); ok && len(resp) > 0 {
		b.WriteString("## Responsibilities\n\n")
		for _, item := range resp {
			b.WriteString(fmt.Sprintf("- %v\n", item))
		}
		b.WriteString("\n")
	}
	if esc, ok := role["escalation"].(map[string]any); ok && len(esc) > 0 {
		b.WriteString("## Escalation\n\n")
		if v, ok := esc["ifBlockedBy"]; ok {
			b.WriteString(fmt.Sprintf("- If blocked by: %v\n", v))
		}
		if notify, ok := esc["notify"].([]any); ok && len(notify) > 0 {
			b.WriteString("- Notify:")
			for _, n := range notify {
				b.WriteString(fmt.Sprintf(" `%v`", n))
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	b.WriteString("Generated by Agent Operating Kit from pack role content.\n")
	return b.String()
}

func cursorSkillMD(packDir string, skill map[string]any, slug string) (string, error) {
	name := orString(skill["name"], orString(skill["id"], slug))
	desc := orString(skill["description"], "AOK skill "+name)
	sourcePath := orString(skill["sourcePath"], "")
	if sourcePath != "" {
		src := filepath.Join(packDir, filepath.FromSlash(sourcePath))
		data, err := os.ReadFile(src)
		if err == nil {
			text := string(data)
			if strings.HasPrefix(strings.TrimSpace(text), "---") {
				// Ensure frontmatter name matches folder (Cursor requirement).
				return rewriteSkillFrontmatter(text, slug, desc), nil
			}
			var b strings.Builder
			b.WriteString("---\n")
			b.WriteString(fmt.Sprintf("name: %s\n", slug))
			b.WriteString(fmt.Sprintf("description: %q\n", desc))
			b.WriteString("---\n\n")
			b.WriteString(text)
			if !strings.HasSuffix(text, "\n") {
				b.WriteString("\n")
			}
			return b.String(), nil
		}
	}

	var b strings.Builder
	b.WriteString("---\n")
	b.WriteString(fmt.Sprintf("name: %s\n", slug))
	b.WriteString(fmt.Sprintf("description: %q\n", desc))
	b.WriteString("---\n\n")
	b.WriteString(fmt.Sprintf("# %s\n\n", name))
	b.WriteString(desc)
	b.WriteString("\n\nGenerated by Agent Operating Kit from pack skill content.\n")
	if inputs, ok := skill["inputs"].(map[string]any); ok && len(inputs) > 0 {
		b.WriteString("\n## Inputs\n\n")
		for k, v := range inputs {
			b.WriteString(fmt.Sprintf("- `%s`: %v\n", k, v))
		}
	}
	return b.String(), nil
}

func rewriteSkillFrontmatter(text, slug, fallbackDesc string) string {
	trimmed := strings.TrimSpace(text)
	parts := strings.SplitN(trimmed, "---", 3)
	if len(parts) < 3 {
		return text
	}
	fm := parts[1]
	body := parts[2]
	lines := strings.Split(fm, "\n")
	var out []string
	haveName, haveDesc := false, false
	for _, line := range lines {
		trim := strings.TrimSpace(line)
		if strings.HasPrefix(trim, "name:") {
			out = append(out, "name: "+slug)
			haveName = true
			continue
		}
		if strings.HasPrefix(trim, "description:") {
			out = append(out, line)
			haveDesc = true
			continue
		}
		out = append(out, line)
	}
	if !haveName {
		out = append([]string{"name: " + slug}, out...)
	}
	if !haveDesc {
		out = append(out, fmt.Sprintf("description: %q", fallbackDesc))
	}
	return "---" + strings.Join(out, "\n") + "---" + body
}

func cursorHooksChecklist(hooks []map[string]any) string {
	var b strings.Builder
	b.WriteString("# Cursor hooks checklist (non-executable)\n\n")
	b.WriteString("AOK emits this file as **operator guidance**, not as\n")
	b.WriteString("`.cursor/hooks.json`. Pack hooks often reference Claude Code\n")
	b.WriteString("plugin paths (`CLAUDE_PLUGIN_ROOT`) and are not Cursor hook\n")
	b.WriteString("scripts. Map manually or keep as a pre/after checklist.\n\n")
	for _, hook := range hooks {
		name := orString(hook["name"], orString(hook["id"], "hook"))
		b.WriteString(fmt.Sprintf("## %s\n\n", name))
		if v := orString(hook["event"], ""); v != "" {
			b.WriteString(fmt.Sprintf("- Event: `%s`\n", v))
		}
		if v := orString(hook["severity"], ""); v != "" {
			b.WriteString(fmt.Sprintf("- Severity: `%s`\n", v))
		}
		if v := orString(hook["description"], ""); v != "" {
			b.WriteString(fmt.Sprintf("- Description: %s\n", v))
		}
		if v := orString(hook["command"], ""); v != "" {
			b.WriteString(fmt.Sprintf("- Source command (not auto-wired): `%s`\n", v))
		}
		b.WriteString("\n")
	}
	return b.String()
}
