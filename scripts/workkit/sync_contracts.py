"""Synchronize authored WorkKit schemas and typed Go resources; --check never writes."""
from pathlib import Path
import argparse,json,shutil,tempfile,subprocess
ROOT=Path(__file__).resolve().parents[2]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--design',type=Path,default=(ROOT.parent/'workkit-design' if (ROOT.parent/'workkit-design').is_dir() else ROOT/'kits/workkit'))
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
D=args.design
if args.check:
 temp=tempfile.TemporaryDirectory(prefix='workkit-contracts-')
 A=Path(temp.name)
else:A=ROOT
for directory in ['kits/workkit/schemas','kits/workkit/api/v1alpha1']:(A/directory).mkdir(parents=True,exist_ok=True)
for p in (D/'schemas').glob('*.json'):shutil.copyfile(p,A/'kits/workkit/schemas'/p.name)
def pascal(s):
 return s[:1].upper()+s[1:]
defs={};types={};metadata={'type':'object','properties':{'id':{'type':'string'},'revision':{'type':'integer'}},'required':['id','revision']}
def typefor(s,name):
 if '$ref'in s:return pascal(s['$ref'].split('/')[-1])
 t=s.get('type')
 if t=='object' and 'properties'in s:
  if name not in types:
   types[name]=''
   required=set(s.get('required',[]));fields=[]
   for k,v in s['properties'].items():
    typ=typefor(v,name+pascal(k));optional=k not in required
    if optional:typ='*'+typ
    fields.append('\t'+pascal(k)+' '+typ+' `json:"'+k+(',omitempty' if optional else '')+'"`')
   types[name]='type '+name+' struct {\n'+'\n'.join(fields)+'\n}\n'
  return name
 if t=='array':return '[]'+typefor(s['items'],name+'Item')
 if t=='object':return 'map[string]json.RawMessage'
 if t=='integer':return 'int64'
 if t=='number':return 'json.Number'
 if t=='boolean' or isinstance(s.get('const'),bool):return 'bool'
 if t=='string' or 'enum'in s or isinstance(s.get('const'),str):return 'string'
 return 'json.RawMessage'
common=json.loads((D/'schemas/common.schema.json').read_text())
for name,s in common['$defs'].items():
 n=pascal(name);t=typefor(s,n)
 if n not in types:types[n]='type '+n+' '+t+'\n'
typefor(metadata,'Metadata')
kinds=[]
for p in sorted((D/'schemas').glob('*.json')):
 v=json.loads(p.read_text())
 if 'title'not in v:continue
 kind=v['title'];spec=typefor(v['properties']['spec'],kind+'Spec');kinds.append(kind)
 types[kind]='type '+kind+' = Resource['+spec+']\n'
text='// Code generated by scripts/workkit/sync_contracts.py; DO NOT EDIT.\npackage v1alpha1\n\nimport "encoding/json"\n\nconst Version = "workkit/v1alpha1"\n\ntype Resource[T any] struct {\n APIVersion string `json:"apiVersion"`\n Kind string `json:"kind"`\n Metadata Metadata `json:"metadata"`\n Spec T `json:"spec"`\n Extensions map[string]json.RawMessage `json:"extensions,omitempty"`\n}\n\n'+'\n'.join(types.values())
(A/'kits/workkit/api/v1alpha1/types_generated.go').write_text(text)
(A/'kits/workkit/schemas/embed.go').write_text('''// Package schemas supplies pinned offline WorkKit schemas.
package schemas
import "embed"
//go:embed *.json
var Files embed.FS
''')

subprocess.run(['gofmt','-w',str(A/'kits/workkit/api/v1alpha1/types_generated.go'),str(A/'kits/workkit/schemas/embed.go')],check=True)
if args.check:
 for p in A.rglob('*'):
  if p.is_file():
   target=ROOT/p.relative_to(A)
   if not target.exists() or target.read_bytes()!=p.read_bytes():raise SystemExit('contract drift: '+str(target))
 print('WorkKit schema/type synchronization passed')
